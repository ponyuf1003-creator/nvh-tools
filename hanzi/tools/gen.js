// ---------- 组词启发式 ----------
function isHan(s){ return /^[一-鿿]+$/.test(s); }
function pickWords(c) {
  if (WORDS[c]) return WORDS[c];
  let cand = [];
  try { cand = cnchar.words(c) || []; } catch(e) {}
  const myIdx = idxOf[c];
  const scored = cand.filter(w => w.length === 2 && isHan(w) && w.includes(c)).map(w => {
    const other = w.replace(c, '') || c;
    let score = 0;
    if (charSet.has(other)) {
      score += 3;
      if (idxOf[other] < myIdx) score += 2;       // 另一个字学过 → 滚雪球
    }
    return { w, score };
  });
  scored.sort((a,b) => b.score - a.score);
  const out = [];
  for (const {w} of scored) {
    if (!out.includes(w)) out.push(w);
    if (out.length >= 2) break;
  }
  // 兜底：三字词
  if (out.length === 0) {
    const three = cand.filter(w => w.length === 3 && isHan(w));
    if (three.length) out.push(three[0]);
  }
  return out;
}

